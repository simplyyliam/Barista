use tauri_specta::{collect_commands, Builder};

/// Where the generated TypeScript bindings go (relative to src-tauri). Never edit that file.
const BINDINGS_PATH: &str = "../src/shared/bindings.ts";

/// Lists every command the frontend may call. bindings.ts is generated from this list.
fn specta_builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new().commands(collect_commands![commands::get_version])
}

/// Writes bindings.ts (on debug runs and in `cargo test`, i.e. `pnpm gen`).
fn export_bindings(builder: &Builder<tauri::Wry>) {
    let ts = specta_typescript::Typescript::default().header(
        "// GENERATED by tauri-specta from apps/bar/src-tauri. Do not edit by hand.\n// @ts-nocheck",
    );
    builder
        .export(ts, BINDINGS_PATH)
        .expect("failed to export TypeScript bindings");
}

pub fn run() {
    let builder = specta_builder();
    #[cfg(debug_assertions)]
    export_bindings(&builder);

    tauri::Builder::default()
        .invoke_handler(builder.invoke_handler())
        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}

#[cfg(test)]
mod tests {
    /// `pnpm gen` runs this. CI then fails on `git diff` if the committed bindings were stale.
    #[test]
    fn export_bindings() {
        super::export_bindings(&super::specta_builder());
    }
}
