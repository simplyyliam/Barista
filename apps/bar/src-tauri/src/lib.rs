//! Barista's native side. The frontend only renders state it gets from here (CLAUDE.md rule 5).

mod bar;
mod commands;
mod controller;
mod events;
mod ipc;
mod platform;
mod registry;
mod settings;
mod tray;

use tauri_specta::{collect_commands, collect_events, Builder};

/// Where the generated TypeScript bindings go. Anchored on the crate folder (not the current
/// directory), so it works however the app is started. Never edit that file.
const BINDINGS_PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../src/shared/bindings.ts");

/// Lists every command the frontend may call. bindings.ts is generated from this list.
fn specta_builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            commands::get_version,
            commands::get_bar_info,
            commands::set_monitor
        ])
        .events(collect_events![events::BarChanged])
}

/// Writes bindings.ts (on debug runs and in `cargo test`, i.e. `pnpm gen`).
fn export_bindings(builder: &Builder<tauri::Wry>) -> Result<(), Box<dyn std::error::Error>> {
    let ts = specta_typescript::Typescript::default().header(
        "// GENERATED by tauri-specta from apps/bar/src-tauri. Do not edit by hand.\n// @ts-nocheck",
    );
    builder.export(ts, BINDINGS_PATH)?;
    Ok(())
}

pub fn run() {
    let builder = specta_builder();
    // A failed export (read-only file, ...) must not stop the app from starting.
    #[cfg(debug_assertions)]
    if let Err(error) = export_bindings(&builder) {
        eprintln!("could not write bindings.ts: {error}");
    }

    tauri::Builder::default()
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);
            controller::start(app.handle())?;
            Ok(())
        })
        .build(tauri::generate_context!())
        .expect("error while building tauri application")
        .run(|_app, event| {
            // Give the reserved screen space back on a normal quit.
            if let tauri::RunEvent::Exit = event {
                if let Some(c) = controller::get() {
                    c.shutdown();
                }
            }
        });
}

#[cfg(test)]
mod tests {
    /// `pnpm gen` runs this. CI then fails on `git diff` if the committed bindings were stale.
    #[test]
    fn export_bindings() {
        super::export_bindings(&super::specta_builder()).expect("failed to export bindings");
    }
}
